"""Markdown and JSON report generation."""
import json
import re
from pathlib import Path

from llm.fallback import CATEGORY_TITLES


def to_json(analysis: dict) -> str:
    return json.dumps(analysis, indent=2, default=str)


def to_markdown(analysis: dict) -> str:
    repo, stats, summary, meta = analysis["repository"], analysis["statistics"], analysis["summary"], analysis["meta"]
    generated = "Gemini AI" if summary["generated_by"] == "gemini" else "rule-based fallback (no AI)"
    out = [
        f"# Repository Report: {repo['name']}", "",
        f"- **Source:** {meta['source']}", f"- **Analyzed at:** {meta['analyzed_at']}",
        f"- **Active branch:** {repo['active_branch']}",
        f"- **Commits analyzed:** {stats['total_commits']} (repository total: {repo['total_commits']})",
        f"- **Contributors:** {len(stats['contributors'])}", f"- **Branches:** {repo['branch_count']}",
        f"- **Summary generated by:** {generated}", "",
        "## Summary", "", summary["summary"], "", "## Major Changes", "",
        *[f"- {m}" for m in summary["major_changes"]], "", "## Development Insights", "",
        *[f"- {m}" for m in summary["development_insights"]], "", "## Changelog", "", summary["changelog"], "",
        "## Commit Categories", "", "| Category | Commits | Share |", "|---|---|---|",
        *[f"| {CATEGORY_TITLES[c]} | {n} | {stats['category_percent'][c]}% |" for c, n in stats["category_counts"].items()],
        "", "## Most Frequently Changed Files", "", "| File | Commits | Added | Removed | Authors |", "|---|---|---|---|---|",
        *[f"| `{f['path']}` | {f['commits']} | {f['insertions']} | {f['deletions']} | {f['authors']} |" for f in stats["top_files"][:10]],
        "", "## Contributors", "", "| Author | Commits | Share | Added | Removed |", "|---|---|---|---|---|",
        *[f"| {c['author']} | {c['commits']} | {c['share']}% | {c['insertions']} | {c['deletions']} |" for c in stats["contributors"]],
        "", "## Risks and Patterns (evidence-based)", "",
        *([f"- **[{i['severity']}] {i['title']}** - {'; '.join(i['evidence'])}" for i in analysis["insights"]] or ["- None detected"]),
        "", "## Recent Commits", "", "| Commit | Date | Author | Category | Message |", "|---|---|---|---|---|",
        *[f"| `{c['short_sha']}` | {c['date'][:10]} | {c['author']} | {CATEGORY_TITLES[c['category']]} | {c['message'].replace('|', '/')} |"
          for c in analysis["commits"][:30]],
        "",
    ]
    return "\n".join(out)


def save_reports(analysis: dict, directory) -> dict:
    """Write both reports into `directory` and return their paths."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    stamp = analysis["meta"]["analyzed_at"][:19].replace(":", "").replace("-", "").replace("T", "_")
    base = f"{re.sub(r'[^A-Za-z0-9_.-]+', '_', analysis['repository']['name'])}_{stamp}"
    md_path, json_path = directory / f"{base}.md", directory / f"{base}.json"
    md_path.write_text(to_markdown(analysis), encoding="utf-8")
    json_path.write_text(to_json(analysis), encoding="utf-8")
    return {"markdown": md_path, "json": json_path}
