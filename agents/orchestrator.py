"""Agent 5 - Orchestrator: runs the other agents in order and passes results between them.

Workflow:  open repo -> Inspector -> extract commits -> Classifier -> Insight Analyst -> Summary Generator -> save
Each step's output is the next step's input. Gemini is used only by the Summary Generator (and the Q&A box).
"""
import time
from datetime import datetime, timezone

from agents.commit_classifier import CommitClassifier
from agents.insight_analyst import InsightAnalyst
from agents.repository_inspector import RepositoryInspector
from agents.summary_generator import SummaryGenerator
from backend import config, extractor


class Orchestrator:
    def __init__(self, gemini=None, db=None):
        self.gemini = gemini
        self.db = db
        self.inspector = RepositoryInspector()
        self.classifier = CommitClassifier()
        self.analyst = InsightAnalyst()
        self.summarizer = SummaryGenerator(gemini)

    def run(self, source: str, max_commits: int = config.DEFAULT_MAX_COMMITS, use_ai: bool = True, progress=None) -> dict:
        from backend.git_utils import open_repository

        max_commits = max(1, min(int(max_commits), config.HARD_MAX_COMMITS))
        progress = progress or (lambda fraction, message: None)
        progress(0.05, "Opening repository...")
        repo, name = open_repository(source)
        log = []

        progress(0.15, "Repository Inspector: reading metadata and structure...")
        repo_info = self._step(log, self.inspector.name, lambda: self.inspector.run(repo, source, name),
                               lambda r: f"{r['total_commits']} commits, {r['branch_count']} branches, {r['file_count']} files")

        progress(0.3, "Extracting commits and diffs from Git...")
        commits = self._step(log, "Git Extractor", lambda: extractor.extract_commits(repo, max_commits),
                             lambda r: f"{len(r)} commits read")
        return self.analyze_data(repo_info, commits, source, max_commits, use_ai, progress, log)

    def analyze_data(self, repo_info, commits, source, max_commits, use_ai=True, progress=None, log=None) -> dict:
        progress = progress or (lambda fraction, message: None)
        log = log if log is not None else []

        progress(0.5, "Commit Classifier: categorizing commits...")
        commits = self._step(log, self.classifier.name, lambda: self.classifier.run(commits),
                             lambda r: f"{len(r)} commits classified")

        progress(0.65, "Insight Analyst: looking for hotspots and risks...")
        analysis = self._step(log, self.analyst.name, lambda: self.analyst.run(repo_info, commits),
                              lambda r: f"{len(r['insights'])} insights")
        stats, insights = analysis["statistics"], analysis["insights"]

        progress(0.8, "Summary Generator: writing summary and changelog...")
        summary = self._step(log, self.summarizer.name,
                             lambda: self.summarizer.run(repo_info, commits, stats, insights, use_ai),
                             lambda r: f"generated by {r['generated_by']}")

        for c in commits:
            c.pop("diff_excerpt", None)
        result = {
            "meta": {
                "analyzed_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                "source": source, "max_commits": max_commits,
                "ai_used": summary["generated_by"] == "gemini", "ai_error": summary["ai_error"],
                "model": summary.get("model"),
            },
            "repository": repo_info, "commits": commits, "statistics": stats,
            "insights": insights, "summary": summary, "workflow": log,
        }
        if self.db is not None:
            progress(0.95, "Saving analysis to SQLite...")
            result["id"] = self.db.save_analysis(result)
        progress(1.0, "Done")
        return result

    @staticmethod
    def _step(log, agent_name, func, describe):
        started = time.perf_counter()
        output = func()
        log.append({"agent": agent_name, "seconds": round(time.perf_counter() - started, 2), "detail": describe(output)})
        return output
